SELECT b.Title, 
       GROUP_CONCAT(CONCAT(a.FirstName, ' ', a.LastName) SEPARATOR ', ') AS Authors,
       COUNT(ld.CopyID) AS TimesBorrowed
FROM Book b
JOIN BOOK_AUTHOR ba ON b.BookID = ba.BookID
JOIN Author a ON ba.AuthorID = a.AuthorID
JOIN BOOK_COPY bc ON b.BookID = bc.BookID
JOIN LOAN_DETAILS ld ON bc.CopyID = ld.CopyID
GROUP BY b.BookID
ORDER BY TimesBorrowed DESC
LIMIT 5;

SELECT m.MemberID, CONCAT(m.FirstName, ' ', m.LastName) AS FullName,
       COUNT(l.LoanID) AS ActiveLoans
FROM Member m
JOIN Loan l ON m.MemberID = l.MemberID
WHERE l.Status = 'Borrowed'
GROUP BY m.MemberID
ORDER BY ActiveLoans DESC;

SELECT b.Title, 
       ROUND(AVG(r.Score), 2) AS AverageRating
FROM Book b
JOIN Rating r ON b.BookID = r.BookID
GROUP BY b.BookID
HAVING AverageRating < 3;

SELECT b.Title, b.BookID
FROM Book b
JOIN BOOK_COPY bc ON b.BookID = bc.BookID
LEFT JOIN LOAN_DETAILS ld ON bc.CopyID = ld.CopyID
LEFT JOIN Loan l ON ld.LoanID = l.LoanID
GROUP BY b.BookID
HAVING MAX(l.LoanDate) IS NULL OR MAX(l.LoanDate) < CURDATE() - INTERVAL 6 MONTH;

SELECT b.Title, 
       COUNT(bc.CopyID) AS TotalCopies,
       SUM(CASE WHEN bc.AvailabilityStatus = 'Available' THEN 1 ELSE 0 END) AS AvailableCopies
FROM Book b
JOIN BOOK_COPY bc ON b.BookID = bc.BookID
GROUP BY b.BookID;





