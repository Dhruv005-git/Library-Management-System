-- Create Publisher table
CREATE TABLE Publisher (
    PublisherID VARCHAR(50) PRIMARY KEY,
    Name VARCHAR(255) NOT NULL,
    Address VARCHAR(255),
    ContactNumber VARCHAR(50),
    Email VARCHAR(100)
);

-- Create Book table
CREATE TABLE Book (
    BookID VARCHAR(50) PRIMARY KEY,
    Title VARCHAR(255) NOT NULL,
    PublicationYear INT,
    Language VARCHAR(50),
    Pages INT,
    Summary TEXT,
    PublisherID VARCHAR(50),
    FOREIGN KEY (PublisherID) REFERENCES Publisher(PublisherID)
);

-- Create Author table
CREATE TABLE Author (
    AuthorID VARCHAR(50) PRIMARY KEY,
    FirstName VARCHAR(100),
    LastName VARCHAR(100),
    Biography TEXT,
    Nationality VARCHAR(100),
    Genre VARCHAR(100)  -- Primary genre of the author’s work
);

-- Create Genre table
CREATE TABLE Genre (
    GenreID VARCHAR(50) PRIMARY KEY,
    Name VARCHAR(100),
    Description TEXT
);

-- Create Member table
CREATE TABLE Member (
    MemberID VARCHAR(50) PRIMARY KEY,
    FirstName VARCHAR(100),
    LastName VARCHAR(100),
    Email VARCHAR(100),
    Phone VARCHAR(50),
    Address VARCHAR(255),
    MembershipDate DATE,
    MembershipType VARCHAR(50)
);

-- Create Staff table
CREATE TABLE Staff (
    StaffID VARCHAR(50) PRIMARY KEY,
    FirstName VARCHAR(100),
    LastName VARCHAR(100),
    Email VARCHAR(100),
    Phone VARCHAR(50),
    Role VARCHAR(50),
    HireDate DATE
);

-- Create Loan table
CREATE TABLE Loan (
    LoanID VARCHAR(50) PRIMARY KEY,
    MemberID VARCHAR(50),
    IssuedBy VARCHAR(50),
    ReceivedBy VARCHAR(50),
    LoanDate DATE,
    DueDate DATE,
    ReturnDate DATE,
    Status VARCHAR(50),
    FOREIGN KEY (MemberID) REFERENCES Member(MemberID),
    FOREIGN KEY (IssuedBy) REFERENCES Staff(StaffID),
    FOREIGN KEY (ReceivedBy) REFERENCES Staff(StaffID)
);

-- Create Rating table
CREATE TABLE Rating (
    RatingID VARCHAR(50) PRIMARY KEY,
    BookID VARCHAR(50),
    MemberID VARCHAR(50),
    Score INT,
    FOREIGN KEY (BookID) REFERENCES Book(BookID),
    FOREIGN KEY (MemberID) REFERENCES Member(MemberID)
);

-- Create Review table
CREATE TABLE Review (
    ReviewID VARCHAR(50) PRIMARY KEY,
    BookID VARCHAR(50),
    MemberID VARCHAR(50),
    ReviewText TEXT,
    FOREIGN KEY (BookID) REFERENCES Book(BookID),
    FOREIGN KEY (MemberID) REFERENCES Member(MemberID)
);

-- Create Book_Copy table
CREATE TABLE Book_Copy (
    CopyID VARCHAR(50) PRIMARY KEY,
    BookID VARCHAR(50),
    ManagedBy VARCHAR(50),
    AcquisitionDate DATE,
    ConditionOfBook VARCHAR(50),
    AvailabilityStatus VARCHAR(50),
    Location VARCHAR(100),
    FOREIGN KEY (BookID) REFERENCES Book(BookID),
    FOREIGN KEY (ManagedBy) REFERENCES Staff(StaffID)
);

-- Create Interlibrary_Loan table
CREATE TABLE Interlibrary_Loan (
    InterlibraryLoanID VARCHAR(50) PRIMARY KEY,
    BookID VARCHAR(50),
    MemberID VARCHAR(50),
    LoanDate DATE,
    DueDate DATE,
    ReturnDate DATE,
    LibraryName VARCHAR(255),
    FOREIGN KEY (BookID) REFERENCES Book(BookID),
    FOREIGN KEY (MemberID) REFERENCES Member(MemberID)
);

-- Create Keyword table
CREATE TABLE Keyword (
    KeywordID VARCHAR(50) PRIMARY KEY,
    Word VARCHAR(100)
);

-- Create Join Table: BOOK_AUTHOR
CREATE TABLE BOOK_AUTHOR (
    BookID VARCHAR(50),
    AuthorID VARCHAR(50),
    PRIMARY KEY (BookID, AuthorID),
    FOREIGN KEY (BookID) REFERENCES Book(BookID),
    FOREIGN KEY (AuthorID) REFERENCES Author(AuthorID)
);

-- Create Join Table: BOOK_GENRE
CREATE TABLE BOOK_GENRE (
    BookID VARCHAR(50),
    GenreID VARCHAR(50),
    PRIMARY KEY (BookID, GenreID),
    FOREIGN KEY (BookID) REFERENCES Book(BookID),
    FOREIGN KEY (GenreID) REFERENCES Genre(GenreID)
);

-- Create Join Table: BOOK_KEYWORD
CREATE TABLE BOOK_KEYWORD (
    BookID VARCHAR(50),
    KeywordID VARCHAR(50),
    PRIMARY KEY (BookID, KeywordID),
    FOREIGN KEY (BookID) REFERENCES Book(BookID),
    FOREIGN KEY (KeywordID) REFERENCES Keyword(KeywordID)
);

-- Create Join Table: LOAN_DETAILS
CREATE TABLE LOAN_DETAILS (
    LoanID VARCHAR(50),
    CopyID VARCHAR(50),
    PRIMARY KEY (LoanID, CopyID),
    FOREIGN KEY (LoanID) REFERENCES Loan(LoanID),
    FOREIGN KEY (CopyID) REFERENCES Book_Copy(CopyID)
);

